//! `aurora-locus deploy caddyfile`: the Caddyfile for a certificate
//! strategy. Locus never edits Caddy's files; this prints one for the
//! installer or the operator to put in place.

use std::fmt::Write as _;

/// How Caddy gets certificates.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum Strategy {
    /// On-demand per name, each approved by `/tls-check` (the default).
    OnDemand,
    /// A DNS-01 wildcard for the PDS hostname and handle domain, through a
    /// DNS provider module (the `locus-caddy` image), on-demand for the rest.
    Dns01,
    /// Behind Cloudflare's proxy: a fixed origin certificate, no ACME.
    Cloudflare,
}

/// What the Caddyfile is made from.
pub struct Options {
    pub strategy: Strategy,
    /// Where locus listens, from Caddy's side.
    pub upstream: String,
    /// The `/tls-check` URL Caddy asks.
    pub ask_url: String,
    /// The ACME account contact.
    pub email: String,
    /// The PDS hostname (DNS-01 and Cloudflare).
    pub hostname: String,
    /// The handle domain's wildcard, as `example.com` (DNS-01 and
    /// Cloudflare); empty for none.
    pub wildcard: String,
    /// The Caddy DNS provider module (DNS-01), e.g. `cloudflare`.
    pub dns_provider: String,
    /// The origin certificate and key files (Cloudflare).
    pub cert: String,
    pub key: String,
    /// Cloudflare's ranges, for Caddy's `trusted_proxies`.
    pub cloudflare_ranges: Vec<String>,
}

fn global(o: &Options, out: &mut String) {
    out.push_str("{\n");
    if o.strategy != Strategy::Cloudflare && !o.email.is_empty() {
        let _ = writeln!(out, "\temail {}", o.email);
    }
    if o.strategy != Strategy::Cloudflare {
        let _ = writeln!(out, "\ton_demand_tls {{\n\t\task {}\n\t}}", o.ask_url);
    }
    out.push_str("\tservers {\n\t\tstrict_sni_host on\n");
    if o.strategy == Strategy::Cloudflare {
        let _ = writeln!(
            out,
            "\t\ttrusted_proxies static {}",
            o.cloudflare_ranges.join(" ")
        );
    }
    out.push_str("\t}\n}\n\n");
}

fn names(o: &Options) -> String {
    let mut n = vec![o.hostname.clone()];
    if !o.wildcard.is_empty() {
        n.push(format!(
            "*.{}",
            o.wildcard.trim_start_matches("*.").trim_start_matches('.')
        ));
    }
    n.join(", ")
}

/// The Caddyfile, or why it can't be made.
pub fn caddyfile(o: &Options) -> Result<String, String> {
    let mut out = String::from("# Generated by `aurora-locus deploy caddyfile`.\n");
    global(o, &mut out);
    match o.strategy {
        Strategy::OnDemand => {}
        Strategy::Dns01 => {
            if o.hostname.is_empty() || o.dns_provider.is_empty() {
                return Err(
                    "dns01 needs --hostname and --dns-provider (and usually --wildcard)".into(),
                );
            }
            let _ = writeln!(
                out,
                "{} {{\n\ttls {{\n\t\tdns {} {{env.DNS_API_TOKEN}}\n\t}}\n\treverse_proxy {}\n}}\n",
                names(o),
                o.dns_provider,
                o.upstream
            );
        }
        Strategy::Cloudflare => {
            if o.cert.is_empty() || o.key.is_empty() {
                return Err("cloudflare needs --cert and --key (the Cloudflare Origin CA certificate and key)".into());
            }
            let site = if o.hostname.is_empty() {
                "https://".to_owned()
            } else {
                names(o)
            };
            let _ = writeln!(
                out,
                "{site} {{\n\ttls {} {}\n\treverse_proxy {}\n}}",
                o.cert, o.key, o.upstream
            );
            return Ok(out);
        }
    }
    // Every other name: on demand, if /tls-check approves it.
    let _ = writeln!(
        out,
        "https:// {{\n\ttls {{\n\t\ton_demand\n\t}}\n\treverse_proxy {}\n}}",
        o.upstream
    );
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn opts(strategy: Strategy) -> Options {
        Options {
            strategy,
            upstream: "locus:3000".into(),
            ask_url: "http://locus:3000/tls-check".into(),
            email: "admin@example.com".into(),
            hostname: "pds.example.com".into(),
            wildcard: "example.com".into(),
            dns_provider: "cloudflare".into(),
            cert: "/certs/origin.pem".into(),
            key: "/certs/origin.key".into(),
            cloudflare_ranges: vec!["173.245.48.0/20".into(), "2400:cb00::/32".into()],
        }
    }

    #[test]
    fn every_variant_keeps_strict_sni_and_its_certificates() {
        let d = caddyfile(&opts(Strategy::OnDemand)).unwrap();
        assert!(
            d.contains("email admin@example.com") && d.contains("ask http://locus:3000/tls-check")
        );
        assert!(
            d.contains("strict_sni_host on") && d.contains("https:// {") && d.contains("on_demand")
        );
        let w = caddyfile(&opts(Strategy::Dns01)).unwrap();
        assert!(
            w.contains("pds.example.com, *.example.com {")
                && w.contains("dns cloudflare {env.DNS_API_TOKEN}")
        );
        assert!(
            w.contains("on_demand") && w.contains("strict_sni_host on"),
            "names outside the wildcard stay on demand"
        );
        let c = caddyfile(&opts(Strategy::Cloudflare)).unwrap();
        assert!(
            c.contains("tls /certs/origin.pem /certs/origin.key")
                && c.contains("trusted_proxies static 173.245.48.0/20 2400:cb00::/32")
        );
        assert!(
            !c.contains("on_demand") && !c.contains("email") && c.contains("strict_sni_host on")
        );
        let mut bad = opts(Strategy::Cloudflare);
        bad.cert.clear();
        assert!(caddyfile(&bad).is_err());
        let mut bad = opts(Strategy::Dns01);
        bad.dns_provider.clear();
        assert!(caddyfile(&bad).is_err());
    }
}
